import {FIREBASE_SDK_VERSION,firebaseConfig} from './firebase-config.js?v=0.11.0-alpha.42';

const BUILD='0.11.0-alpha.54';
const MODE_KEY='vta-workspace-mode-v01';
const PLANTS_KEY='abwasser-plants-v07';
const ACTIVE_PLANT_KEY='abwasser-active-plant-v07';
const PLANT_PAGE_KEY='abwasser-plant-page-v091a';
const FILTER_KEY='vta-cloud-task-filter-v01';
const TASKS='tasks';

const TASK_TYPES={
  general:{label:'Aufgabe',icon:'✓'},
  call:{label:'Anruf',icon:'☎'},
  scheduling:{label:'Termin vereinbaren',icon:'◷'},
  email:{label:'E-Mail',icon:'✉'},
  followup:{label:'Nachfassen',icon:'↻'},
  review:{label:'Kontrolle',icon:'◎'},
  technical:{label:'Technische Maßnahme',icon:'⚙'},
  commercial:{label:'Angebot / Bestellung',icon:'€'},
  'spare-part':{label:'Ersatzteil',icon:'▣'}
};

let firestoreApi=null;
let auth=null;
let db=null;
let unsubscribe=null;
let cloudTasks=new Map();
let ready=false;
let scheduled=false;
let started=false;

const session=()=>window.VTAFirebaseSession||null;
const uid=()=>session()?.user?.uid||session()?.profile?.uid||'';
const role=()=>session()?.role||'';
const manager=()=>['admin','teamlead'].includes(role());
const online=()=>Boolean(session()?.authenticated&&!session()?.offline&&localStorage.getItem(MODE_KEY)!=='demo');
const esc=value=>String(value??'').replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const meta=type=>TASK_TYPES[type]||TASK_TYPES.general;

function readPlants(){
  try{const value=JSON.parse(localStorage.getItem(PLANTS_KEY)||'[]');return Array.isArray(value)?value:[]}
  catch{return []}
}
function localTask(taskId){
  for(const plant of readPlants()){
    const action=(plant.actions||[]).find(item=>String(item?.id||'')===String(taskId));
    if(action)return {plant,action};
  }
  return null;
}
function cacheLocal(task){
  const plants=readPlants();
  const plant=plants.find(item=>String(item?.id||'')===String(task.plantId||''));
  if(!plant)return;
  plant.actions=Array.isArray(plant.actions)?plant.actions:[];
  const incoming={
    id:String(task.id),title:String(task.title||'Aufgabe'),description:String(task.description||''),status:String(task.status||'open'),
    priority:String(task.priority||'normal'),dueDate:String(task.dueDate||''),component:String(task.component||''),sourceVisitId:String(task.sourceVisitId||''),
    createdAt:String(task.createdAt||new Date().toISOString()),completedAt:String(task.completedAt||''),autoGenerated:Boolean(task.autoGenerated),
    followUpType:String(task.followUpType||''),followUpSourceId:String(task.followUpSourceId||''),taskType:String(task.taskType||'general'),
    contactName:String(task.contactName||''),completionOutcome:String(task.completionOutcome||''),cloudTaskId:String(task.id),
    assignedToUserId:String(task.assignedToUserId||''),assignedToName:String(task.assignedToName||''),createdByUserId:String(task.createdByUserId||''),
    createdByName:String(task.createdByName||''),updatedAt:String(task.updatedAt||'')
  };
  const index=plant.actions.findIndex(action=>String(action?.id||'')===String(task.id));
  if(index>=0)plant.actions[index]={...plant.actions[index],...incoming};else plant.actions.push(incoming);
  localStorage.setItem(PLANTS_KEY,JSON.stringify(plants));
}
function removeLocal(taskId){
  const plants=readPlants();let changed=false;
  for(const plant of plants){
    const before=(plant.actions||[]).length;
    plant.actions=(plant.actions||[]).filter(action=>!(String(action?.id||'')===String(taskId)&&action.cloudTaskId));
    changed=changed||before!==plant.actions.length;
  }
  if(changed)localStorage.setItem(PLANTS_KEY,JSON.stringify(plants));
}

async function ensureFirebase(){
  if(db&&auth?.currentUser)return;
  const base=`https://www.gstatic.com/firebasejs/${FIREBASE_SDK_VERSION}`;
  const [appModule,authModule,firestoreModule]=await Promise.all([
    import(`${base}/firebase-app.js`),import(`${base}/firebase-auth.js`),import(`${base}/firebase-firestore.js`)
  ]);
  firestoreApi=firestoreModule;
  const app=appModule.getApps().length?appModule.getApp():appModule.initializeApp(firebaseConfig);
  auth=authModule.getAuth(app);db=firestoreModule.getFirestore(app);
  if(!auth.currentUser)throw new Error('Keine aktive Firebase-Anmeldung.');
}

function dueLabel(value){
  if(!value)return 'Ohne Fälligkeit';
  const date=new Date(`${String(value).slice(0,10)}T00:00:00`);
  return Number.isNaN(date.getTime())?String(value):date.toLocaleDateString('de-DE');
}
function priorityLabel(value){return value==='high'?'Hohe Priorität':'Normal'}
function filterMode(){return manager()&&localStorage.getItem(FILTER_KEY)==='all'?'all':'mine'}
function visibleFor(task){return filterMode()==='all'||!task.assignedToUserId||task.assignedToUserId===uid()}

function cardHtml(task){
  const type=meta(task.taskType),plant=task.plantName||localTask(task.id)?.plant?.master?.name||'Kläranlage';
  return `<article class="global-task-card task-type-${esc(task.taskType||'general')} ${task.priority==='high'?'high':''}" data-action-id="${esc(task.id)}" data-plant-id="${esc(task.plantId||'')}" data-cloud-global-card="${BUILD}">
    <div class="task-type-badge"><span class="task-type-icon">${esc(type.icon)}</span>${esc(type.label)}</div>
    <div class="task-content"><span>${esc(plant)}</span><strong>${esc(task.title||'Aufgabe')}</strong>
      <div class="task-meta"><span>${esc(dueLabel(task.dueDate))}</span><span>${esc(priorityLabel(task.priority))}</span>${task.assignedToName?`<span>Zuständig: ${esc(task.assignedToName)}</span>`:''}</div>
    </div>
    <div class="task-actions"><button type="button" data-cloud-complete-task="${esc(task.id)}">Erledigt</button><button type="button" data-cloud-open-plant="${esc(task.plantId||'')}">Anlage öffnen</button></div>
  </article>`;
}

function ensureEmptyState(list){
  const visible=[...list.querySelectorAll('[data-action-id]')].some(card=>!card.hidden);
  list.querySelectorAll('.empty-panel:not(.firebase-cloud-task-empty)').forEach(panel=>panel.hidden=visible||cloudTasks.size>0);
  let empty=list.querySelector('.firebase-cloud-task-empty');
  if(visible){empty?.remove();return}
  if(!empty){empty=document.createElement('div');empty.className='empty-panel firebase-cloud-task-empty';list.append(empty)}
  empty.innerHTML=filterMode()==='mine'?'<h2>Keine eigenen offenen Aufgaben</h2><p>Unter „Alle“ siehst du als Admin bzw. Teamleitung die Aufgaben des Teams.</p>':'<h2>Keine offenen Aufgaben</h2><p>Aktuell sind keine offenen Cloud-Aufgaben vorhanden.</p>';
}

function reconcile(){
  const list=document.querySelector('.global-task-list');if(!list)return;
  for(const task of cloudTasks.values()){
    const id=String(task.id||'');if(!id)continue;
    let card=list.querySelector(`[data-action-id="${CSS.escape(id)}"]`);
    if(task.status==='done'){
      if(card?.dataset.cloudGlobalCard)card.remove();else if(card)card.hidden=true;
      continue;
    }
    if(!card){list.insertAdjacentHTML('beforeend',cardHtml(task));card=list.querySelector(`[data-action-id="${CSS.escape(id)}"]`)}
    if(card){card.hidden=!visibleFor(task);card.dataset.cloudTaskKnown='1'}
  }
  if(ready){
    list.querySelectorAll('[data-action-id][data-cloud-task-known]').forEach(card=>{
      const id=String(card.dataset.actionId||'');
      if(cloudTasks.has(id))return;
      if(card.dataset.cloudGlobalCard)card.remove();else card.hidden=true;
    });
    list.querySelectorAll('[data-cloud-global-card]').forEach(card=>{if(!cloudTasks.has(String(card.dataset.actionId||'')))card.remove()});
  }
  const cards=[...list.querySelectorAll('[data-action-id]')];
  cards.sort((a,b)=>{
    const ta=cloudTasks.get(String(a.dataset.actionId||''))||localTask(a.dataset.actionId)?.action||{};
    const tb=cloudTasks.get(String(b.dataset.actionId||''))||localTask(b.dataset.actionId)?.action||{};
    return String(ta.dueDate||'9999-12-31').localeCompare(String(tb.dueDate||'9999-12-31'))||String(ta.title||'').localeCompare(String(tb.title||''));
  }).forEach(card=>list.append(card));
  ensureEmptyState(list);
}
function queue(){if(scheduled)return;scheduled=true;requestAnimationFrame(()=>{scheduled=false;reconcile()})}

async function completeTask(taskId){
  const task=cloudTasks.get(String(taskId));if(!task)return;
  await ensureFirebase();
  const now=new Date().toISOString();
  await firestoreApi.updateDoc(firestoreApi.doc(db,TASKS,String(taskId)),{status:'done',completedAt:now,updatedAt:now,updatedByUserId:uid()});
  const updated={...task,status:'done',completedAt:now,updatedAt:now,updatedByUserId:uid()};
  cloudTasks.set(String(taskId),updated);cacheLocal(updated);
  window.dispatchEvent(new CustomEvent('vta:cloud-tasks-updated',{detail:{reason:'global-cloud-complete',build:BUILD}}));
  queue();
}
function openPlant(plantId){
  if(!plantId)return;
  const select=document.querySelector('#activePlantSelect');
  if(!select||![...select.options].some(option=>option.value===String(plantId))){
    alert('Die zugehörige Anlage ist auf diesem Gerät noch nicht lokal verfügbar. Die Aufgabe bleibt trotzdem in der Cloud-Übersicht sichtbar.');
    return;
  }
  localStorage.setItem(ACTIVE_PLANT_KEY,String(plantId));localStorage.setItem(PLANT_PAGE_KEY,'tasks');
  select.value=String(plantId);select.dispatchEvent(new Event('change',{bubbles:true}));
  setTimeout(()=>document.querySelector('[data-plant-page="tasks"]')?.click(),80);
}

async function subscribe(){
  unsubscribe?.();unsubscribe=null;ready=false;
  if(!online()){cloudTasks.clear();queue();return}
  try{
    await ensureFirebase();
    const base=firestoreApi.collection(db,TASKS);
    const source=manager()?base:firestoreApi.query(base,firestoreApi.where('assignedToUserId','==',uid()));
    unsubscribe=firestoreApi.onSnapshot(source,snapshot=>{
      ready=true;
      snapshot.docChanges().forEach(change=>{
        const id=String(change.doc.id);
        if(change.type==='removed'){cloudTasks.delete(id);removeLocal(id)}
        else{const task={id,...change.doc.data()};cloudTasks.set(id,task);cacheLocal(task)}
      });
      queue();
    },error=>{ready=false;console.error('Cloud-Gesamtübersicht Aufgaben',error);queue()});
  }catch(error){ready=false;console.error('Cloud-Gesamtübersicht Aufgaben Start',error);queue()}
}

function bind(){
  document.addEventListener('click',event=>{
    const complete=event.target.closest?.('[data-cloud-complete-task]');
    if(complete){event.preventDefault();complete.disabled=true;completeTask(complete.dataset.cloudCompleteTask).catch(error=>{console.error(error);alert('Die Aufgabe konnte nicht als erledigt gespeichert werden.');complete.disabled=false});return}
    const plant=event.target.closest?.('[data-cloud-open-plant]');if(plant){event.preventDefault();openPlant(plant.dataset.cloudOpenPlant);return}
    const filter=event.target.closest?.('#firebaseTaskCloudToolbar [data-filter]');if(filter)setTimeout(queue,0);
  },true);
  const root=document.querySelector('#mainContent')||document.body;
  new MutationObserver(queue).observe(root,{childList:true,subtree:true});
  window.addEventListener('vta:firebase-session',subscribe);
  window.addEventListener('vta:cloud-tasks-updated',queue);
  window.addEventListener('vta:task-assignment-changed',queue);
  window.addEventListener('pageshow',()=>{queue();subscribe()});
  document.addEventListener('visibilitychange',()=>{if(!document.hidden){queue();subscribe()}});
}
function init(){if(started)return;started=true;bind();subscribe();queue()}

window.VTAGlobalCloudTasks={build:BUILD,get ready(){return ready},get tasks(){return [...cloudTasks.values()]},refresh:queue};
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init,{once:true});else init();
