import {FIREBASE_SDK_VERSION,firebaseConfig} from './firebase-config.js?v=0.11.0-alpha.42';

const BUILD='0.11.0-alpha.44';
const MODE_KEY='vta-workspace-mode-v01';
const PLANTS_KEY='abwasser-plants-v07';
const ACTIVE_PLANT_KEY='abwasser-active-plant-v07';
const COLLECTION='tasks';
const USERS_COLLECTION='users';
const FILTER_KEY='vta-cloud-task-filter-v01';

let authApi=null;
let firestoreApi=null;
let auth=null;
let db=null;
let unsubscribeTasks=null;
let users=[];
let cloudReady=false;
let cloudError='';
let started=false;
let decorateQueued=false;
let syncQueued=false;
let applyingCloud=false;
let lastTaskFingerprints=new Map();
let legacyTaskIds=new Set();
let pendingAssignment=null;

const session=()=>window.VTAFirebaseSession||null;
const isDemo=()=>localStorage.getItem(MODE_KEY)==='demo';
const currentUid=()=>session()?.user?.uid||session()?.profile?.uid||'';
const currentRole=()=>session()?.role||'';
const isManager=()=>['admin','teamlead'].includes(currentRole());
const isOnlineSession=()=>Boolean(session()?.authenticated&&!session()?.offline&&!isDemo());
const esc=value=>String(value??'').replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));

function readPlants(){
  try{
    const parsed=JSON.parse(localStorage.getItem(PLANTS_KEY)||'[]');
    return Array.isArray(parsed)?parsed:[];
  }catch(error){
    console.warn('Cloud-Aufgaben: lokale Anlagen konnten nicht gelesen werden',error);
    return [];
  }
}

function writePlants(plants,reason='cloud-task-sync'){
  try{
    applyingCloud=true;
    localStorage.setItem(PLANTS_KEY,JSON.stringify(plants));
    window.dispatchEvent(new CustomEvent('vta:cloud-tasks-updated',{detail:{reason,build:BUILD}}));
    return true;
  }catch(error){
    console.error('Cloud-Aufgaben: lokaler Cache konnte nicht aktualisiert werden',error);
    return false;
  }finally{
    applyingCloud=false;
  }
}

function allLocalTasks(plants=readPlants()){
  return plants.flatMap(plant=>(Array.isArray(plant?.actions)?plant.actions:[]).map(action=>({plant,action})));
}

function activePlantId(){
  return localStorage.getItem(ACTIVE_PLANT_KEY)||'';
}

function userLabel(profile){
  const name=[profile?.firstName,profile?.lastName].filter(Boolean).join(' ').trim();
  return name||profile?.name||profile?.email||'Mitarbeiter';
}

function currentUserLabel(){
  return userLabel(session()?.profile||session()?.user||{});
}

function taskFingerprint(action){
  const keys=['title','status','priority','dueDate','taskType','contactName','completedAt','completionOutcome','assignedToUserId','assignedToName'];
  return keys.map(key=>`${key}:${String(action?.[key]??'')}`).join('|');
}

function rememberLocalState(){
  lastTaskFingerprints=new Map();
  allLocalTasks().forEach(({action})=>{
    if(action?.id)lastTaskFingerprints.set(action.id,taskFingerprint(action));
  });
}

function seedLegacyTasks(){
  legacyTaskIds=new Set(
    allLocalTasks()
      .filter(({action})=>action?.id&&!action.cloudTaskId&&!action.cloudPending)
      .map(({action})=>action.id)
  );
}

function findLocalTask(taskId,plants=readPlants()){
  for(const plant of plants){
    const action=(plant.actions||[]).find(item=>item?.id===taskId||item?.cloudTaskId===taskId);
    if(action)return {plant,action};
  }
  return null;
}

function assigneeById(uid){
  return users.find(user=>user.uid===uid)||null;
}

function selectedAssigneeForForm(form){
  const select=form?.querySelector('[name="assignedToUserId"]');
  const uid=select?.value||currentUid();
  const profile=assigneeById(uid);
  return {uid,name:profile?userLabel(profile):(uid===currentUid()?currentUserLabel():'Mitarbeiter')};
}

function cloudDocument(plant,action,{assignedToUserId,assignedToName}={}){
  const uid=currentUid();
  const now=new Date().toISOString();
  const assignedUid=assignedToUserId||action.assignedToUserId||uid;
  const assignedName=assignedToName||action.assignedToName||(assigneeById(assignedUid)?userLabel(assigneeById(assignedUid)):(assignedUid===uid?currentUserLabel():'Mitarbeiter'));
  return {
    id:String(action.id),
    cloudVersion:1,
    plantId:String(plant.id||''),
    plantName:String(plant?.master?.name||'Kläranlage'),
    title:String(action.title||'Aufgabe'),
    description:String(action.description||''),
    status:String(action.status||'open'),
    priority:String(action.priority||'normal'),
    dueDate:String(action.dueDate||''),
    taskType:String(action.taskType||'general'),
    contactName:String(action.contactName||''),
    component:String(action.component||''),
    sourceVisitId:String(action.sourceVisitId||''),
    autoGenerated:Boolean(action.autoGenerated),
    followUpType:String(action.followUpType||''),
    followUpSourceId:String(action.followUpSourceId||''),
    completionOutcome:String(action.completionOutcome||''),
    completedAt:String(action.completedAt||''),
    assignedToUserId:String(assignedUid),
    assignedToName:String(assignedName),
    createdByUserId:String(action.createdByUserId||uid),
    createdByName:String(action.createdByName||currentUserLabel()),
    createdAt:String(action.createdAt||now),
    updatedAt:now,
    updatedByUserId:String(uid)
  };
}

function localActionFromCloud(data){
  return {
    id:String(data.id||''),
    title:String(data.title||'Aufgabe'),
    status:String(data.status||'open'),
    priority:String(data.priority||'normal'),
    dueDate:String(data.dueDate||''),
    component:String(data.component||''),
    sourceVisitId:String(data.sourceVisitId||''),
    createdAt:String(data.createdAt||new Date().toISOString()),
    completedAt:String(data.completedAt||''),
    autoGenerated:Boolean(data.autoGenerated),
    followUpType:String(data.followUpType||''),
    followUpSourceId:String(data.followUpSourceId||''),
    taskType:String(data.taskType||'general'),
    contactName:String(data.contactName||''),
    completionOutcome:String(data.completionOutcome||''),
    assignedToUserId:String(data.assignedToUserId||''),
    assignedToName:String(data.assignedToName||''),
    createdByUserId:String(data.createdByUserId||''),
    createdByName:String(data.createdByName||''),
    updatedAt:String(data.updatedAt||''),
    cloudTaskId:String(data.id||''),
    cloudVersion:Number(data.cloudVersion||1),
    cloudPending:false
  };
}

async function ensureFirebase(){
  if(db&&auth?.currentUser)return {db,user:auth.currentUser};
  const base=`https://www.gstatic.com/firebasejs/${FIREBASE_SDK_VERSION}`;
  const [appModule,authModule,firestoreModule]=await Promise.all([
    import(`${base}/firebase-app.js`),
    import(`${base}/firebase-auth.js`),
    import(`${base}/firebase-firestore.js`)
  ]);
  authApi=authModule;
  firestoreApi=firestoreModule;
  const firebaseApp=appModule.getApps().length?appModule.getApp():appModule.initializeApp(firebaseConfig);
  auth=authModule.getAuth(firebaseApp);
  db=firestoreModule.getFirestore(firebaseApp);
  if(!auth.currentUser)throw new Error('Keine aktive Firebase-Anmeldung.');
  return {db,user:auth.currentUser};
}

async function loadUsers(){
  if(!isOnlineSession())return;
  await ensureFirebase();
  if(isManager()){
    const snapshot=await firestoreApi.getDocs(firestoreApi.collection(db,USERS_COLLECTION));
    users=snapshot.docs.map(doc=>({uid:doc.id,...doc.data()})).filter(user=>user.active!==false);
  }else{
    const profile=session()?.profile||{};
    users=[{uid:currentUid(),...profile}];
  }
  if(!users.some(user=>user.uid===currentUid()))users.unshift({uid:currentUid(),...(session()?.profile||{})});
}

function readableError(error){
  const code=String(error?.code||'');
  if(code.includes('permission-denied'))return 'Firestore-Regeln für Cloud-Aufgaben sind noch nicht freigeschaltet.';
  if(code.includes('network')||code==='unavailable')return 'Firebase ist momentan nicht erreichbar.';
  return error?.message||'Cloud-Aufgaben konnten nicht synchronisiert werden.';
}

function applyCloudTask(data){
  const plants=readPlants();
  const plant=plants.find(item=>item.id===data.plantId);
  if(!plant)return false;
  plant.actions=Array.isArray(plant.actions)?plant.actions:[];
  const incoming=localActionFromCloud(data);
  const index=plant.actions.findIndex(action=>action.id===incoming.id||action.cloudTaskId===incoming.id);
  if(index>=0)plant.actions[index]={...plant.actions[index],...incoming};
  else plant.actions.push(incoming);
  legacyTaskIds.delete(incoming.id);
  return writePlants(plants,'cloud-upsert');
}

function removeCloudTask(taskId){
  const plants=readPlants();
  let changed=false;
  for(const plant of plants){
    const before=(plant.actions||[]).length;
    plant.actions=(plant.actions||[]).filter(action=>action.cloudTaskId!==taskId);
    if(plant.actions.length!==before)changed=true;
  }
  if(changed)writePlants(plants,'cloud-remove');
}

async function subscribeCloudTasks(){
  unsubscribeTasks?.();
  unsubscribeTasks=null;
  if(!isOnlineSession())return;
  await ensureFirebase();
  const base=firestoreApi.collection(db,COLLECTION);
  const source=isManager()?base:firestoreApi.query(base,firestoreApi.where('assignedToUserId','==',currentUid()));
  unsubscribeTasks=firestoreApi.onSnapshot(source,snapshot=>{
    cloudReady=true;
    cloudError='';
    snapshot.docChanges().forEach(change=>{
      if(change.type==='removed')removeCloudTask(change.doc.id);
      else applyCloudTask({id:change.doc.id,...change.doc.data()});
    });
    rememberLocalState();
    queueDecorate();
  },error=>{
    cloudReady=false;
    cloudError=readableError(error);
    console.error('Cloud-Aufgaben Listener',error);
    queueDecorate();
  });
}

async function createCloudTask(plant,action,assignment={}){
  if(!isOnlineSession())return false;
  await ensureFirebase();
  const record=cloudDocument(plant,action,assignment);
  await firestoreApi.setDoc(firestoreApi.doc(db,COLLECTION,String(action.id)),record);
  const plants=readPlants();
  const local=findLocalTask(action.id,plants);
  if(local){
    Object.assign(local.action,{
      assignedToUserId:record.assignedToUserId,
      assignedToName:record.assignedToName,
      createdByUserId:record.createdByUserId,
      createdByName:record.createdByName,
      updatedAt:record.updatedAt,
      cloudTaskId:record.id,
      cloudVersion:1,
      cloudPending:false
    });
    writePlants(plants,'cloud-created');
  }
  legacyTaskIds.delete(action.id);
  return true;
}

async function updateCloudTask(plant,action){
  if(!action?.cloudTaskId||!isOnlineSession())return;
  await ensureFirebase();
  const ref=firestoreApi.doc(db,COLLECTION,String(action.cloudTaskId));
  const now=new Date().toISOString();
  if(isManager()){
    const record=cloudDocument(plant,action);
    await firestoreApi.setDoc(ref,record,{merge:true});
  }else{
    await firestoreApi.updateDoc(ref,{
      status:String(action.status||'open'),
      completedAt:String(action.completedAt||''),
      completionOutcome:String(action.completionOutcome||''),
      updatedAt:now,
      updatedByUserId:currentUid()
    });
  }
}

async function reassignCloudTask(taskId,assignedUid){
  if(!isManager()||!isOnlineSession())return;
  const match=findLocalTask(taskId);
  if(!match?.action?.cloudTaskId)return;
  const profile=assigneeById(assignedUid);
  const name=profile?userLabel(profile):'Mitarbeiter';
  await ensureFirebase();
  await firestoreApi.updateDoc(firestoreApi.doc(db,COLLECTION,match.action.cloudTaskId),{
    assignedToUserId:assignedUid,
    assignedToName:name,
    updatedAt:new Date().toISOString(),
    updatedByUserId:currentUid()
  });
  const plants=readPlants();
  const local=findLocalTask(taskId,plants);
  if(local){
    local.action.assignedToUserId=assignedUid;
    local.action.assignedToName=name;
    local.action.updatedAt=new Date().toISOString();
    writePlants(plants,'cloud-reassign');
  }
}

async function deleteCloudTask(taskId){
  if(!isManager()||!isOnlineSession())return;
  await ensureFirebase();
  await firestoreApi.deleteDoc(firestoreApi.doc(db,COLLECTION,String(taskId)));
}

function markNewUnsyncedTask(actionId,assignment){
  const plants=readPlants();
  const local=findLocalTask(actionId,plants);
  if(!local)return null;
  Object.assign(local.action,{
    assignedToUserId:assignment?.uid||currentUid(),
    assignedToName:assignment?.name||currentUserLabel(),
    createdByUserId:local.action.createdByUserId||currentUid(),
    createdByName:local.action.createdByName||currentUserLabel(),
    cloudPending:true
  });
  writePlants(plants,'cloud-pending');
  return {plant:local.plant,action:local.action};
}

async function syncLocalChanges(){
  if(syncQueued||applyingCloud||!isOnlineSession())return;
  syncQueued=true;
  try{
    const plants=readPlants();
    const newTasks=[];
    const changed=[];
    for(const plant of plants){
      for(const action of plant.actions||[]){
        if(!action?.id)continue;
        const fingerprint=taskFingerprint(action);
        const old=lastTaskFingerprints.get(action.id);
        if(action.cloudTaskId&&old&&old!==fingerprint)changed.push({plant,action});
        if(!action.cloudTaskId&&(action.cloudPending||(!legacyTaskIds.has(action.id)&&!lastTaskFingerprints.has(action.id))))newTasks.push({plant,action});
      }
    }

    for(const item of newTasks){
      const assignment=pendingAssignment&&pendingAssignment.plantId===item.plant.id?pendingAssignment.assignment:null;
      const marked=markNewUnsyncedTask(item.action.id,assignment);
      if(!marked)continue;
      try{await createCloudTask(marked.plant,marked.action,assignment||{})}
      catch(error){cloudError=readableError(error);console.error('Neue Cloud-Aufgabe konnte nicht angelegt werden',error)}
    }
    pendingAssignment=null;

    for(const item of changed){
      try{await updateCloudTask(item.plant,item.action)}
      catch(error){cloudError=readableError(error);console.error('Cloud-Aufgabe konnte nicht aktualisiert werden',error)}
    }
    rememberLocalState();
  }finally{
    syncQueued=false;
    queueDecorate();
  }
}

function legacyCandidates(){
  return allLocalTasks().filter(({action})=>action?.id&&action.status!=='done'&&!action.cloudTaskId);
}

async function migrateLegacyTasks(){
  const candidates=legacyCandidates();
  if(!candidates.length)return;
  const message=`${candidates.length} offene lokale Aufgabe${candidates.length===1?'':'n'} in die Cloud übernehmen?\n\nDie Aufgaben werden zunächst dir (${currentUserLabel()}) zugewiesen und können danach von Administratoren/Teamleitungen umverteilt werden.`;
  if(!window.confirm(message))return;
  let success=0;
  for(const {plant,action} of candidates){
    try{
      const marked=markNewUnsyncedTask(action.id,{uid:currentUid(),name:currentUserLabel()});
      if(marked){await createCloudTask(marked.plant,marked.action);success+=1}
    }catch(error){
      cloudError=readableError(error);
      console.error('Lokale Aufgabe konnte nicht migriert werden',error);
      break;
    }
  }
  rememberLocalState();
  queueDecorate();
  if(success)window.alert(`${success} Aufgabe${success===1?'':'n'} wurde${success===1?'':'n'} in die Cloud übernommen.`);
}

function assigneeOptions(selected=''){
  return users.map(user=>`<option value="${esc(user.uid)}" ${user.uid===selected?'selected':''}>${esc(userLabel(user))}</option>`).join('');
}

function decorateQuickForm(){
  const form=document.querySelector('#quickActionForm');
  if(!form||form.querySelector('[name="assignedToUserId"]'))return;
  const submit=form.querySelector('button[type="submit"]');
  if(!submit)return;
  const select=document.createElement('select');
  select.name='assignedToUserId';
  select.className='firebase-task-assignee-select';
  select.setAttribute('aria-label','Aufgabe zuweisen');
  select.innerHTML=assigneeOptions(currentUid());
  if(!isManager())select.disabled=true;
  const label=document.createElement('label');
  label.className='firebase-task-assignee-field';
  label.innerHTML='<span>Zuständig</span>';
  label.append(select);
  form.insertBefore(label,submit);
}

function decorateTaskCards(){
  document.querySelectorAll('[data-action-id][data-plant-id]').forEach(card=>{
    const taskId=card.dataset.actionId;
    const match=findLocalTask(taskId);
    if(!match)return;
    let host=card.querySelector('.firebase-task-assignee');
    if(!host){
      host=document.createElement('div');
      host.className='firebase-task-assignee';
      const content=card.querySelector('.task-content')||card;
      content.append(host);
    }
    const action=match.action;
    if(!action.cloudTaskId){
      host.innerHTML='<span class="firebase-task-local-chip">Nur lokal</span>';
      return;
    }
    if(isManager()){
      host.innerHTML=`<label>Zuständig <select data-cloud-task-assignee="${esc(action.id)}">${assigneeOptions(action.assignedToUserId||currentUid())}</select></label><span class="firebase-task-cloud-chip">Cloud</span>`;
      const select=host.querySelector('select');
      select?.addEventListener('change',async()=>{
        select.disabled=true;
        try{await reassignCloudTask(action.id,select.value)}
        catch(error){cloudError=readableError(error);console.error(error);queueDecorate()}
        finally{select.disabled=false}
      });
    }else{
      host.innerHTML=`<span class="firebase-task-assignee-name">Zuständig: ${esc(action.assignedToName||currentUserLabel())}</span><span class="firebase-task-cloud-chip">Cloud</span>`;
      card.querySelectorAll('[data-delete-action]').forEach(button=>{button.hidden=true});
    }
  });
}

function currentFilter(){
  if(!isManager())return 'mine';
  return localStorage.getItem(FILTER_KEY)==='all'?'all':'mine';
}

function applyTaskFilter(){
  const list=document.querySelector('.global-task-list');
  if(!list)return;
  const filter=currentFilter();
  list.querySelectorAll('[data-action-id][data-plant-id]').forEach(card=>{
    const match=findLocalTask(card.dataset.actionId);
    if(!match)return;
    const uid=match.action.assignedToUserId||'';
    card.hidden=filter==='mine'&&uid&&uid!==currentUid();
  });
}

function decorateGlobalToolbar(){
  const list=document.querySelector('.global-task-list');
  if(!list)return;
  let bar=document.querySelector('#firebaseTaskCloudToolbar');
  if(!bar){
    bar=document.createElement('section');
    bar.id='firebaseTaskCloudToolbar';
    bar.className='firebase-task-toolbar';
    list.before(bar);
  }
  const candidates=legacyCandidates().length;
  const status=cloudReady?'Cloud synchronisiert':cloudError||'Cloud wird verbunden …';
  const filter=currentFilter();
  bar.innerHTML=`<div class="firebase-task-toolbar-status"><span class="firebase-task-dot ${cloudReady?'ok':cloudError?'error':'loading'}"></span><div><strong>${esc(status)}</strong><small>${esc(currentUserLabel())} · ${esc(currentRole()||'Mitarbeiter')}</small></div></div>
    <div class="firebase-task-toolbar-actions">
      ${isManager()?`<div class="firebase-task-filter" role="group" aria-label="Aufgabenfilter"><button type="button" data-cloud-task-filter="mine" class="${filter==='mine'?'active':''}">Meine</button><button type="button" data-cloud-task-filter="all" class="${filter==='all'?'active':''}">Alle</button></div>`:''}
      ${candidates?`<button type="button" class="button secondary compact" id="firebaseMigrateLocalTasks">${candidates} lokale Aufgabe${candidates===1?'':'n'} übernehmen</button>`:''}
    </div>`;
  bar.querySelectorAll('[data-cloud-task-filter]').forEach(button=>button.addEventListener('click',()=>{
    localStorage.setItem(FILTER_KEY,button.dataset.cloudTaskFilter);
    queueDecorate();
  }));
  bar.querySelector('#firebaseMigrateLocalTasks')?.addEventListener('click',migrateLegacyTasks);
  applyTaskFilter();
}

function queueDecorate(){
  if(decorateQueued)return;
  decorateQueued=true;
  requestAnimationFrame(()=>{
    decorateQueued=false;
    decorateQuickForm();
    decorateTaskCards();
    decorateGlobalToolbar();
  });
}

function bindDomHooks(){
  document.addEventListener('submit',event=>{
    const form=event.target;
    if(form?.id==='quickActionForm'){
      pendingAssignment={plantId:activePlantId(),assignment:selectedAssigneeForForm(form)};
    }
    window.setTimeout(syncLocalChanges,60);
  },true);

  document.addEventListener('click',event=>{
    const button=event.target.closest?.('[data-toggle-action],[data-task-action],[data-delete-action],[data-followup-custom-submit]');
    if(!button)return;
    const cloudDelete=button.matches('[data-delete-action]')?findLocalTask(button.dataset.deleteAction):null;
    const cloudTaskId=cloudDelete?.action?.cloudTaskId||'';
    window.setTimeout(async()=>{
      await syncLocalChanges();
      if(cloudTaskId&&button.matches('[data-delete-action]')&&isManager()){
        const stillLocal=findLocalTask(button.dataset.deleteAction);
        if(!stillLocal){
          try{await deleteCloudTask(cloudTaskId)}catch(error){cloudError=readableError(error);console.error(error)}
        }
      }
    },80);
  },true);

  const main=document.querySelector('#mainContent');
  if(main){
    const observer=new MutationObserver(queueDecorate);
    observer.observe(main,{childList:true,subtree:true});
  }
  window.addEventListener('vta:cloud-tasks-updated',queueDecorate);
  window.addEventListener('pageshow',()=>{queueDecorate();syncLocalChanges()});
  document.addEventListener('visibilitychange',()=>{if(!document.hidden){queueDecorate();syncLocalChanges()}});
}

async function startForSession(){
  if(!isOnlineSession()){
    unsubscribeTasks?.();
    unsubscribeTasks=null;
    cloudReady=false;
    queueDecorate();
    return;
  }
  try{
    await ensureFirebase();
    await loadUsers();
    await subscribeCloudTasks();
    await syncLocalChanges();
  }catch(error){
    cloudReady=false;
    cloudError=readableError(error);
    console.error('Cloud-Aufgaben konnten nicht gestartet werden',error);
    queueDecorate();
  }
}

function initialize(){
  if(started)return;
  started=true;
  seedLegacyTasks();
  rememberLocalState();
  bindDomHooks();
  startForSession();
}

window.VTACloudTasks={
  build:BUILD,
  get ready(){return cloudReady},
  get error(){return cloudError},
  get users(){return users.slice()},
  sync:syncLocalChanges,
  migrateLocal:migrateLegacyTasks
};

window.addEventListener('vta:firebase-session',()=>startForSession());
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',initialize,{once:true});
else initialize();
